import assert from 'node:assert/strict';
import { build, version } from 'esbuild';
import { gzipSync, brotliCompressSync, constants } from 'node:zlib';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const pkg = JSON.parse(await readFile('package.json', 'utf8'));
const budgets = JSON.parse(await readFile('tests/bundle/budgets.json', 'utf8'));
const operators = {
  withHook: 'with-hook', withStaticProps: 'with-static-props', mapProps: 'map-props',
  withGuard: 'with-guard', withSuspense: 'with-suspense', withErrorBoundary: 'with-error-boundary',
  withContext: 'with-context', withWrapper: 'with-wrapper',
};
const rows = [];
async function measure(name, contents) {
  const result = await build({
    stdin: { contents, resolveDir: process.cwd(), sourcefile: `${name}.js` },
    bundle: true, write: false, metafile: true, minify: true,
    format: 'esm', platform: 'browser', target: 'es2020',
    external: ['react', 'react/*', 'react-dom', 'react-dom/*'],
    define: { 'process.env.NODE_ENV': '"production"' },
  });
  const output = result.outputFiles[0].contents;
  const retained = Object.values(result.metafile.outputs).flatMap(out =>
    Object.entries(out.inputs).filter(([,info]) => info.bytesInOutput > 0).map(([path]) => path));
  const row = {
    name, minified: output.length, gzip: gzipSync(output, { level: 9 }).length,
    brotli: brotliCompressSync(output, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).length,
    retained,
  };
  rows.push(row);
  return row;
}
for (const [name, path] of Object.entries(operators)) {
  const root = await measure(name, `export { ${name} } from '${pkg.name}';`);
  const direct = await measure(`${name}/subpath`, `export { ${name} } from '${pkg.name}/${path}';`);
  // Compare the exact retained modules, not the parsed-module list: esbuild parses unused barrels too.
  for (const row of [root, direct]) {
    assert(!row.retained.some(p => p.includes('node_modules')), `${name} must not pull in Effect or integration libraries`);
    assert(row.retained.every(p => p.endsWith(`/dist/${path}.js`) || p === `dist/${path}.js`), `${name} retained another operator`);
    assert(row.gzip <= budgets.maxGzip[name], `${name} exceeded its gzip budget`);
  }
  assert.equal(root.minified, direct.minified, `${name} barrel and subpath should retain the same code`);
}
await measure('pipe', `export { pipe } from '${pkg.name}/pipe';`);
const all = await measure('all HOCs', `export { ${Object.keys(operators).join(', ')} } from '${pkg.name}';`);
const allPipe = await measure('all HOCs + pipe', `export * from '${pkg.name}';`);
assert(all.gzip <= budgets.allGzip, 'All HOCs exceeded their gzip budget');
assert(allPipe.gzip <= budgets.allWithPipeGzip, 'All HOCs + pipe exceeded their gzip budget');
await mkdir('tmp', { recursive: true });
await writeFile('tmp/bundle-sizes.json', JSON.stringify({
  esbuild: version, target: 'es2020', format: 'esm', react: 'external', gzipLevel: 9, brotliQuality: 11, rows,
}, null, 2) + '\n');
if (!process.argv.includes('--check')) {
  console.table(rows.filter(r => !r.name.endsWith('/subpath')).map(({name,minified,gzip,brotli}) => ({name,minified,gzip,brotli})));
}
console.log('Bundle budgets, barrel tree shaking and subpath parity passed.');

if (process.argv.includes('--write-readme')) {
  const text = await readFile('README.md', 'utf8');
  const table = '| Export | Minified bytes | Gzip bytes | Brotli bytes |\n| --- | ---: | ---: | ---: |\n' +
    rows.filter(row => !row.name.endsWith('/subpath')).map(row =>
      `| \`${row.name}\` | ${row.minified} | ${row.gzip} | ${row.brotli} |`).join('\n');
  const block = '<!-- bundle-sizes:start -->\n<!-- Generated by pnpm size:update. Do not edit this table manually. -->\n' + table + '\n<!-- bundle-sizes:end -->';
  assert(text.includes('<!-- bundle-sizes:start -->') && text.includes('<!-- bundle-sizes:end -->'));
  await writeFile('README.md', text.replace(/<!-- bundle-sizes:start -->[\s\S]*?<!-- bundle-sizes:end -->/, block));
}
